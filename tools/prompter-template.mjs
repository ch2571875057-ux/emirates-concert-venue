// 把「排镜台」页面的 HTML 模板单独放一个文件，避免 storyboard.mjs 里塞一坨模板字符串
// 用法：由 tools/storyboard.mjs --prompter 调用 buildPrompterHtml(shots, chapters, base)
export function buildPrompterHtml(shots, chapters, base, showTotal) {
  const data = JSON.stringify(shots.map((s) => ({
    id: s.id, ch: s.ch, title: s.title, dur: s.dur, q: s.q,
    act: s.act, cap: s.cap, note: s.note, main: !!s.main, opt: !!s.opt,
  })));
  const chs = JSON.stringify(chapters);
  return '<!DOCTYPE html>\n' + [
    '<html lang="zh-CN">',
    '<head>',
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1">',
    '<title>排镜台 · 照着一镜一镜拍</title>',
    '<style>',
    ':root{--bg:#0b0f18;--card:#141a26;--line:#2a3444;--txt:#e6eeff;--dim:#8fa0c5;--acc:#6fa8ff;--ok:#4bd18a}',
    '*{box-sizing:border-box}',
    'body{margin:0;background:var(--bg);color:var(--txt);font:14px/1.6 -apple-system,"Segoe UI","Microsoft YaHei",sans-serif}',
    'header{position:sticky;top:0;z-index:9;background:rgba(11,15,24,.94);backdrop-filter:blur(8px);border-bottom:1px solid var(--line);padding:12px 18px}',
    'h1{margin:0 0 6px;font-size:17px;font-weight:600}',
    '.steps{background:#121a27;border:1px solid #24334a;border-radius:10px;padding:12px 16px 12px 34px;margin:0 0 4px;font-size:13px;color:#cbd9ef}',
    '.steps li{margin:5px 0}',
    '.steps b{color:#fff}',
    '.steps code{font-size:11.5px}',
    '.bar{display:flex;align-items:center;gap:12px;flex-wrap:wrap;font-size:12.5px;color:var(--dim)}',
    '.pbar{flex:1;min-width:160px;height:7px;background:#1d2534;border-radius:4px;overflow:hidden}',
    '.pbar>i{display:block;height:100%;width:0;background:linear-gradient(90deg,#4bd18a,#6fa8ff);transition:width .25s}',
    'main{padding:16px 18px 80px;max-width:1180px;margin:0 auto}',
    'h2{font-size:14px;margin:26px 0 10px;color:var(--acc);letter-spacing:.5px}',
    'h2:first-of-type{margin-top:6px}',
    '.card{display:grid;grid-template-columns:82px 1fr;gap:12px;background:var(--card);border:1px solid var(--line);border-radius:10px;padding:12px 14px;margin:8px 0}',
    '.card.done{opacity:.52}',
    '.card.done .sid{color:var(--ok)}',
    '.sid{font:600 15px/1.3 ui-monospace,Consolas,monospace;color:var(--acc)}',
    '.sid small{display:block;font:400 11px/1.4 -apple-system,"Segoe UI","Microsoft YaHei",sans-serif;color:var(--dim);margin-top:3px;letter-spacing:0}',
    '.title{font-weight:600;margin-bottom:3px}',
    '.title .dur{font-weight:400;color:var(--dim);font-size:12px;margin-left:8px}',
    '.act{color:#c9d7f0;font-size:13px;margin:4px 0}',
    '.note{color:var(--dim);font-size:12px;margin-top:4px}',
    '.cap{font-size:12px;color:#a9b8d4;margin-top:4px}',
    '.cap b{color:var(--txt)}',
    '.row{display:flex;gap:8px;align-items:center;flex-wrap:wrap;margin-top:9px}',
    'button{font:inherit;font-size:12.5px;cursor:pointer;border-radius:7px;border:1px solid var(--line);background:#1b2331;color:var(--txt);padding:5px 11px}',
    'button:hover{background:#243046;border-color:#3c4b64}',
    'button.go{background:#22406e;border-color:#3d6bb0;color:#dfeaff}',
    'button.go:hover{background:#2b5088}',
    'button.t{background:#1f3a2c;border-color:#2f6b4c;color:#c9f5dd}',
    'button.t.on{background:#2c6b45;border-color:#4bd18a}',
    'label.ck{display:flex;align-items:center;gap:6px;color:var(--dim);font-size:12.5px;cursor:pointer}',
    'input[type=checkbox]{width:15px;height:15px;accent-color:#4bd18a}',
    'code{font:12px ui-monospace,Consolas,monospace;background:#0d1220;border:1px solid #222c3c;border-radius:5px;padding:2px 6px;color:#9fd0ff;word-break:break-all}',
    '.timer{font:600 15px/1 ui-monospace,Consolas,monospace;color:var(--ok);min-width:64px}',
    '.hint{background:#16202f;border-left:3px solid var(--acc);padding:9px 13px;border-radius:0 8px 8px 0;color:#c4d3ea;font-size:12.5px;margin:10px 0 4px}',
    'footer{position:fixed;left:0;right:0;bottom:0;background:rgba(11,15,24,.94);border-top:1px solid var(--line);padding:8px 18px;font-size:12px;color:var(--dim);display:flex;gap:16px;flex-wrap:wrap}',
    'footer b{color:var(--txt)}',
    '</style>',
    '</head>',
    '<body>',
    '<header>',
    '<h1>排镜台 · 照着一镜一镜拍</h1>',
    '<div class="bar">',
    '<span>已完成 <b id="cnt">0</b> / <b id="total">0</b> 镜</span>',
    '<div class="pbar"><i id="pb"></i></div>',
    '<button id="reset">清空记录</button>',
    '<span>当前站点：<code id="site"></code><em id="site-note"></em></span>',
    '</div>',
    '</header>',
    '<div style="max-width:1180px;margin:0 auto;padding:16px 18px 0">',
    '<ol class="steps">',
    '<li>先把站点跑起来：<b>线上版</b>直接开着本页就行；<b>本地版</b>双击 <b>启动服务器.bat</b>，等黑窗口里出现地址，别关那个窗口。</li>',
    '<li>窗口摆成 <b>1920×1080</b>、缩放 100%；按 <b>F11</b> 全屏、<b>Ctrl+Shift+B</b> 收起书签栏。</li>',
    '<li>录屏软件开 <b>窗口采集</b> 抓这个浏览器窗口，<b>60 帧</b>，声音只收系统声音。</li>',
    '<li>回到本页，从 A1 开始：点 <b>「打开这一镜」</b> → 等进度条走完 → <b>再等 1.5 秒</b> → 点<b>「计时开录」</b> → 录屏软件开录 → 计时器到点就停。</li>',
    '<li>录完勾上 <b>「已录好」</b>，文件名存成镜号（<code>A1.mp4</code>），再点下一镜的「打开这一镜」。</li>',
    '</ol>',
    '</div>',
    '<main id="main"></main>',
    '<footer>',
    '<span>每镜流程：<b>点「打开」→ 等进度条走完 → 再等 1.5 秒 → 点「计时开录」→ 录完打勾</b></span>',
    '<span>钩子存在本机浏览器里，关掉页面也不会丢</span>',
    '</footer>',
    '<script>',
    'var SHOTS=' + data + ';',
    'var CHS=' + chs + ';',
    'var BASE=(function(){var p=location.pathname;'
    +'return location.origin+p.replace(/\\/[^\\/]*$/,"");})();',
    'try{var _s=document.getElementById("site");if(_s)_s.textContent=BASE+"/";'
    +'var _n=document.getElementById("site-note");'
    +'if(_n)_n.textContent=(BASE.indexOf("//127.0.0.1")>0||BASE.indexOf("//localhost")>0?"（本地，录屏首选）":"（线上走 CDN，首屏稍慢）");}catch(e){}',
    'var SHOWTOTAL=' + JSON.stringify(showTotal) + ';',
    'var KEY="concert1.prompter.v1";',
    'var done={};try{done=JSON.parse(localStorage.getItem(KEY)||"{}")||{};}catch(e){done={};}',
    'function save(){try{localStorage.setItem(KEY,JSON.stringify(done));}catch(e){}}',
    'function mmss(sec){var t=Math.round(sec);var m=Math.floor(t/60);var s=t%60;return m+":"+(s<10?"0":"")+s;}',
    'function el(tag,cls,txt){var d=document.createElement(tag);if(cls)d.className=cls;if(txt!=null)d.textContent=txt;return d;}',
    'function urlOf(s){return BASE+"/?"+s.q;}',
    'function render(){',
    '  var main=document.getElementById("main");main.innerHTML="";',
    '  var total=SHOTS.length;',
    '  var n=0;for(var i=0;i<total;i++){if(done[SHOTS[i].id])n++;}',
    '  document.getElementById("cnt").textContent=n;',
    '  document.getElementById("total").textContent=total;',
    '  document.getElementById("pb").style.width=(n/total*100).toFixed(1)+"%";',
    '  CHS.forEach(function(ch){',
    '    var rows=SHOTS.filter(function(s){return s.ch===ch.id;});',
    '    if(!rows.length)return;',
    '    var sum=rows.reduce(function(a,s){return a+s.dur;},0);',
    '    var h=el("h2",null,ch.id+". "+ch.title+"　"+rows.length+" 镜 / 约 "+mmss(sum));',
    '    main.appendChild(h);',
    '    if(ch.id==="A"){main.appendChild(el("div","hint","空镜只能用黄昏（time=17.2–18.5）。19 点以后的鸟瞰/外观全黑，别自己改时间。"));}',
    '    if(ch.id==="B"){main.appendChild(el("div","hint","B0 是主机位全场 62.4 秒，一口气录完；B1–B9 是按 9 段拆开的补镜，挑着录就行。带 showT 的镜：加载后会先跳到那一秒，然后继续往前跑，录晚了这段就过去了 —— 重新点「打开」再来一次。"));}',
    '    if(ch.id==="C"){main.appendChild(el("div","hint","C1 和 C6 需要你手动点面板上的按钮；其余都是打开就录。这几条都很短（3–14 秒），可以连着刷一遍再挑。"));}',
    '    rows.forEach(function(s){main.appendChild(card(s));});',
    '  });',
    '}',
    'function card(s){',
    '  var c=el("div","card"+(done[s.id]?" done":""));',
    '  var left=el("div");',
    '  var sid=el("div","sid",s.id);',
    '  var sm=el("small",null,s.main?"主片":"补镜");',
    '  sid.appendChild(sm);left.appendChild(sid);',
    '  var right=el("div");',
    '  var t=el("div","title",s.title);',
    '  t.appendChild(el("span","dur","· "+s.dur+" s"+(s.opt?" · 可选":"")));',
    '  right.appendChild(t);',
    '  right.appendChild(el("div","act",s.act));',
    '  if(s.cap&&s.cap.indexOf("（")!==0){var cp=el("div","cap");cp.appendChild(document.createTextNode("字幕："));var bb=el("b",null,s.cap);cp.appendChild(bb);right.appendChild(cp);}',
    '  if(s.note)right.appendChild(el("div","note",s.note));',
    '  var row=el("div","row");',
    '  var bOpen=el("button","go","打开这一镜");',
    '  bOpen.onclick=function(){window.open(urlOf(s),"_blank");};',
    '  row.appendChild(bOpen);',
    '  var timer=el("span","timer","0.0s");',
    '  var bT=el("button","t","计时开录");',
    '  var tid=null,t0=0;',
    '  bT.onclick=function(){',
    '    if(tid){clearInterval(tid);tid=null;bT.textContent="计时开录";bT.classList.remove("on");timer.textContent="0.0s";return;}',
    '    t0=Date.now();bT.textContent="停";bT.classList.add("on");',
    '    tid=setInterval(function(){',
    '      var e=(Date.now()-t0)/1000;',
    '      if(e<=s.dur){timer.textContent=e.toFixed(1)+"s";}',
    '      else{timer.textContent="超 "+(e-s.dur).toFixed(1)+"s";}',
    '      if(e>=s.dur&&tid){clearInterval(tid);tid=null;bT.textContent="到了，停录";bT.classList.remove("on");}',
    '    },100);',
    '  };',
    '  row.appendChild(bT);row.appendChild(timer);',
    '  var lab=el("label","ck");',
    '  var cb=document.createElement("input");cb.type="checkbox";cb.checked=!!done[s.id];',
    '  cb.onchange=function(){if(cb.checked){done[s.id]=1;}else{delete done[s.id];}save();render();};',
    '  lab.appendChild(cb);lab.appendChild(document.createTextNode("已录好"));',
    '  row.appendChild(lab);',
    '  var bCopy=el("button",null,"复制地址");',
    '  bCopy.onclick=function(){',
    '    var u=urlOf(s);',
    '    if(navigator.clipboard&&navigator.clipboard.writeText){navigator.clipboard.writeText(u);bCopy.textContent="已复制";}',
    '    else{window.prompt("手动复制这段地址：",u);}',
    '    setTimeout(function(){bCopy.textContent="复制地址";},1200);',
    '  };',
    '  row.appendChild(bCopy);',
    '  right.appendChild(row);',
    '  c.appendChild(left);c.appendChild(right);',
    '  return c;',
    '}',
    'document.getElementById("reset").onclick=function(){if(!confirm("清空所有已录记录？"))return;done={};save();render();};',
    'render();',
    '</script>',
    '</body>',
    '</html>',
    '',
  ].join('\n');
}